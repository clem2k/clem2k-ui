def qss(tokens, theme):
    _, by_theme, _ = resolve(tokens)
    c = by_theme[theme]
    def solid(v):  # Qt QSS accepts rgba(); keep hex/rgba as is
        return v
    edge = c["glass-edge"]
    return QSS.format(theme=theme, ink=c["ink"], inkstrong=c["ink-strong"], muted=c["ink-muted"],
        bg000=c["bg-000"], bg100=c["bg-100"], bg200=c["bg-200"], bg300=c["bg-300"], selection=c["selection"],
        line=c["line"], linestrong=c["line-strong"], neon=c["neon"], neonsoft=c["neon-soft"], onneon=c["on-neon"],
        bot=c["bot"], onbot=c["on-bot"], edge=solid(edge))


def icons():
    grids = json.loads((SRC / "icons.json").read_text())
    (DIST / "icons").mkdir(parents=True, exist_ok=True)
    symbols = []
    for name, g in grids.items():
        rects = []
        for y, row in enumerate(g):
            x = 0
            while x < 12:
                if row[x] == "#":
                    s = x
                    while x < 12 and row[x] == "#":
                        x += 1
                    rects.append(f'<rect x="{s*2}" y="{y*2}" width="{(x-s)*2}" height="2"/>')
                else:
                    x += 1
        body = "".join(rects)
        (DIST / "icons" / f"{name}.svg").write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="currentColor" shape-rendering="crispEdges">{body}</svg>\n')
        symbols.append(f'<symbol id="{name}" viewBox="0 0 24 24">{body}</symbol>')
    (DIST / "icons.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg" style="display:none" fill="currentColor" shape-rendering="crispEdges">' + "".join(symbols) + "</svg>\n")
    return len(grids)


def esm(js):
    """Turn the window.clem2k IIFE into an ES module importing react."""
    body = js.split("\n", 1)[1] if js.startswith("/* @ds-bundle") else js
    body = body.strip()
    assert body.startswith("(function(){") and body.endswith("})();"), "unexpected bundle shape"
    body = body[len("(function(){"):-len("})();")]
    body = body.replace("var R=window.React,", "var R=React,", 1)
    m = re.search(r"var api=\{(.*?)\};", body, re.S)
    names = [kv.split(":")[0] for kv in m.group(1).split(",")]
    body = re.sub(r"window\.clem2k=Object\.assign\(window\.clem2k\|\|\{\},api\);", "", body)
    return ('/* clem2k-ui ES module — generated by scripts/build.py. */\nimport * as React from "react";\n'
            + body + "\nexport { " + ", ".join(names) + " };\nexport default api;\n")


def docs_tokens(tokens):
    themes, by_theme, flat = resolve(tokens)
    usage = {t["name"]: t.get("usage", "") for fam in tokens.values() if isinstance(fam, dict) for t in fam.get("tokens", [])}
    out = ["# Tokens", "", "> Généré par `scripts/build.py` depuis `tokens/tokens.json`. Ne pas éditer à la main.", "",
           "## Couleurs et ombres", "", "| token | " + " | ".join(themes) + " | usage |", "|---|" + "---|" * len(themes) + "---|"]
    for n in by_theme[themes[0]]:
        out.append(f"| `--{n}` | " + " | ".join(f"`{by_theme[t][n]}`" for t in themes) + f" | {usage.get(n, '')} |")
    out += ["", "## Espacements, rayons, flou, polices", "", "| token | valeur | usage |", "|---|---|---|"]
    for n, v in flat.items():
        out.append(f"| `--{n}` | `{v}` | {usage.get(n, '')} |")
    out += ["", "## Styles de texte", "", "Classe utilitaire `ck-t-<nom>` dans `tokens.css`.", "", "| style | taille / interligne | graisse | usage |", "|---|---|---|---|"]
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            out.append(f"| `{s['name']}` | {s['fontSize']} / {s['lineHeight']} | {s['fontWeight']} | {s.get('usage', '')} |")
    return "\n".join(out) + "\n"


def main():
    tokens = load_tokens()
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir()
    tcss = css_tokens(tokens)
    comp = (SRC / "clem2k.css").read_text()
    imp = re.match(r'(@import url\([^)]*\);\s*)', comp)
    imports = imp.group(1) if imp else ""
    comp_body = comp[len(imports):]
    (DIST / "tokens.css").write_text(tcss)
    (DIST / "clem2k.components.css").write_text(HEADER + imports + comp_body)
    (DIST / "clem2k.css").write_text(imports + tcss + "\n" + comp_body)
    shutil.copy(SRC / "clem2k.js", DIST / "clem2k.js")
    shutil.copy(SRC / "clem2k.d.ts", DIST / "clem2k.d.ts")
    (DIST / "clem2k.mjs").write_text(esm((SRC / "clem2k.js").read_text()))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "tokens.md").write_text(docs_tokens(tokens))
    _, by_theme, flat = resolve(tokens)
    (DIST / "tokens.json").write_text(json.dumps({"themes": by_theme, "global": flat, "type": tokens["type"]}, indent=1, ensure_ascii=False))
    (DIST / "tailwind.preset.cjs").write_text(tailwind(tokens))
    (DIST / "clem2k.qss").write_text(qss(tokens, "dark"))
    (DIST / "clem2k-hc.qss").write_text(qss(tokens, "hc"))
    n = icons()
    print(f"dist/ built: tokens ({sum(len(v) for v in by_theme.values())} themed values), {n} icons, tailwind preset, 2 QSS themes")


if __name__ == "__main__":
    main()

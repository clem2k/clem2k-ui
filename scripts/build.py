#!/usr/bin/env python3
"""Build clem2k-ui: tokens/tokens.json + src/ -> dist/.

Pure standard library. Run from the repo root:  python3 scripts/build.py
Outputs (never edit dist/ by hand):
  dist/tokens.css          CSS custom properties, themes dark (default) + hc
  dist/tokens.json         flat resolved tokens {theme: {name: value}}
  dist/clem2k.css          tokens.css + component styles (one file to link)
  dist/clem2k.components.css  component styles only
  dist/clem2k.js           React 18 UMD-style bundle -> window.clem2k
  dist/clem2k.mjs          same components as an ES module (import from "clem2k-ui")
  dist/clem2k.d.ts         types
  docs/tokens.md           token reference table
  dist/tailwind.preset.cjs Tailwind preset bound to the CSS variables
  dist/clem2k.qss          Qt stylesheet (PySide/PyQt), dark theme
  dist/clem2k-hc.qss       Qt stylesheet, High contrast theme
  dist/icons/*.svg         pixel icons, fill=currentColor
  dist/icons.svg           SVG sprite (<use href="icons.svg#terminal">)
"""
import json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, DIST = ROOT / "src", ROOT / "dist"
HEADER = "/* clem2k-ui — generated by scripts/build.py from tokens/tokens.json. Do not edit. */\n"


def load_tokens():
    return json.loads((ROOT / "tokens" / "tokens.json").read_text())


def resolve(tokens):
    """Return {theme_id: {name: value}} for every themable family + flat families."""
    themes = [t["id"] for t in tokens["color"]["themes"]]
    first = themes[0]
    out = {t: {} for t in themes}
    for fam in ("color", "shadow"):
        for tok in tokens.get(fam, {}).get("tokens", []):
            v = tok["value"]
            for th in themes:
                out[th][tok["name"]] = v if isinstance(v, str) else v.get(th, v.get(first))
    flat = {}
    for fam, body in tokens.items():
        if fam in ("color", "shadow", "type", "name", "version") or not isinstance(body, dict):
            continue
        for tok in body.get("tokens", []):
            flat[tok["name"]] = tok["value"]
    for k, stack in tokens["type"]["families"].items():
        flat["font-" + k] = stack
    return themes, out, flat


def css_tokens(tokens):
    themes, by_theme, flat = resolve(tokens)
    lines = [HEADER]
    for i, th in enumerate(themes):
        sel = f':root, [data-theme="{th}"]' if i == 0 else f'[data-theme="{th}"]'
        lines.append(sel + " {")
        lines += [f"  --{n}: {v};" for n, v in by_theme[th].items()]
        lines.append("}")
    lines.append(":root {")
    lines += [f"  --{n}: {v};" for n, v in flat.items()]
    lines.append("}")
    # type styles as utility classes
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            fam = s.get("family", g.get("family"))
            decl = [f"font-family: var(--font-{fam})", f"font-size: {s['fontSize']}",
                    f"line-height: {s['lineHeight']}", f"font-weight: {s['fontWeight']}"]
            if "letterSpacing" in s:
                decl.append(f"letter-spacing: {s['letterSpacing']}")
            if s["name"] == "label":
                decl.append("text-transform: uppercase")
            lines.append(f".ck-t-{s['name']} {{ " + "; ".join(decl) + "; }")
    return "\n".join(lines) + "\n"


def tailwind(tokens):
    _, by_theme, flat = resolve(tokens)
    colors = {n: f"var(--{n})" for n in by_theme[next(iter(by_theme))] if not n.startswith(("focus", "glow", "glass-shadow"))}
    radius = {t["name"].replace("radius-", ""): f"var(--{t['name']})" for t in tokens["radius"]["tokens"]}
    spacing = {t["name"].replace("space-", "ck-"): f"var(--{t['name']})" for t in tokens["spacing"]["tokens"]}
    shadow = {t["name"]: f"var(--{t['name']})" for t in tokens["shadow"]["tokens"]}
    sizes = {}
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            opts = {"lineHeight": s["lineHeight"], "fontWeight": str(s["fontWeight"])}
            if "letterSpacing" in s:
                opts["letterSpacing"] = s["letterSpacing"]
            sizes["ck-" + s["name"]] = [s["fontSize"], opts]
    preset = {"theme": {"extend": {
        "colors": colors, "borderRadius": radius, "spacing": spacing, "boxShadow": shadow,
        "fontFamily": {"mono": ["var(--font-mono)"]}, "fontSize": sizes,
        "backdropBlur": {"glass": "var(--blur-glass)"}}}}
    return "// clem2k-ui Tailwind preset — generated. Load dist/tokens.css (or clem2k.css) in your app too.\nmodule.exports = " + json.dumps(preset, indent=2) + ";\n"


